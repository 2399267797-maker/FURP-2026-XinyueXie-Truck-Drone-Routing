import json
data = json.load(open("PACO+ALNS/results/comparison/raw_results.json", encoding="utf-8"))
lines = []
lines.append("\n## 7. Three-Algorithm Comparison\n")
lines.append("Tested: PACO-imp2, NSGA2-imp, PACO+ALNS-W6 on 10 configs x 3 runs with PyPy.\n")
lines.append("\n### 7.1 Results Table\n")
lines.append("| Config | PACO-imp2 Cost | NSGA2-imp Cost | W6 Cost | PACO-imp2 Tard | NSGA2-imp Tard | W6 Tard |\n")
lines.append("|--------|---------------|----------------|---------|----------------|----------------|---------|\n")
for cfg in sorted(data.keys()):
    parts = cfg.split("_")
    label = parts[0] + "c " + parts[1] + " " + parts[2]
    r = data[cfg]
    pc = r.get("PACO-imp2", {}).get("mean_cost", 0)
    nc = r.get("NSGA2-imp", {}).get("mean_cost", 0)
    wc = r.get("PACO+ALNS-W6", {}).get("mean_cost", 0)
    pt = r.get("PACO-imp2", {}).get("mean_tard", 0)
    nt = r.get("NSGA2-imp", {}).get("mean_tard", 0)
    wt = r.get("PACO+ALNS-W6", {}).get("mean_tard", 0)
    sep = " | "
    lines.append(sep.join(["", label, f"{pc:.1f}", f"{nc:.1f}", f"{wc:.1f}", f"{pt:.1f}", f"{nt:.1f}", f"{wt:.1f}", ""]) + "\n")
lines.append("\n**Note:** W6 and NSGA2-imp costs include capacity/drone-failure penalties. PACO-imp2 solutions are naturally feasible. Compare via Pareto front positions, not absolute cost values.\n")
lines.append("\n### 7.2 Runtime\n")
lines.append("| Scale | PACO-imp2 | NSGA2-imp | W6 |\n")
lines.append("|-------|-----------|-----------|-----|\n")
lines.append("| 25c   | ~10s     | ~1s      | ~40s |\n")
lines.append("| 50c   | ~15s     | ~1s      | ~110s |\n")
lines.append("| 100c  | ~50s     | ~1s      | ~320s |\n")
lines.append("\n### 7.3 Key Findings\n")
lines.append("- PACO-imp2 achieves lowest cost but higher tardiness\n")
lines.append("- W6 achieves lowest tardiness through multi-operator ALNS\n")
lines.append("- NSGA2-imp runs in <1s for all sizes, but solution quality is inconsistent\n")
lines.append("- See PACO+ALNS/results/comparison/plots/ for Pareto front visualizations\n")
result = "".join(lines)
open("PACO+ALNS/results/comparison/report_section.md", "w", encoding="utf-8").write(result)
print("Written", len(result), "bytes")
print(result)
